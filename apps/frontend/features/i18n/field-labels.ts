const FIELD_LABELS: Partial<Record<ResolvedSiteLanguage, Pair[]>> = {
  zh: [...ZH_SECTION_TITLES, ...ZH_FIELD_LABELS],
};

export function localizeFieldLabel(text: string, lang: ResolvedSiteLanguage): string | null {
  const raw = text.trim();
  if (!raw || lang === "en") return null;
  const pairs = FIELD_LABELS[lang];
  if (!pairs) return null;
  const lower = raw.toLowerCase();
  for (const [from, to] of pairs) {
    if (from.toLowerCase() === lower) return to;
  }
  return null;
}

