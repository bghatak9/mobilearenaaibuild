export function getMessages(lang: string): MessageCatalog {
  const partial = PARTIALS[lang];
  const resolved = (
    lang === "zh" || lang === "hi" || lang === "es" ? lang : "en"
  ) as ResolvedSiteLanguage;
  const extra = getUiExtra(resolved);
  const pages = getPageExtra(resolved);
  return { ...EN_MESSAGES, ...extra, ...pages, ...(partial ?? {}) };
}

export function translateMessage(
  lang: string,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let text = getMessages(lang)[key] ?? EN_MESSAGES[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
